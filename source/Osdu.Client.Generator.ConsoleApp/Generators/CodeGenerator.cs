using System.Text;
using Microsoft.Extensions.Logging;
using Osdu.Client.Generator.ConsoleApp.Extensions;
using Osdu.Client.Generator.ConsoleApp.Generators.Api;
using Osdu.Client.Generator.ConsoleApp.Generators.Schema;

namespace Osdu.Client.Generator.ConsoleApp.Generators;

public class CodeGenerator
{
    private readonly ILogger<CodeGenerator> _logger;
    private readonly AppConfiguration _configuration;
    private readonly ApiGenerator _apiGenerator;
    private readonly SchemaGenerator _schemaGenerator;
    private readonly ServiceCollectionExtensionsGenerator _servicesExtensionGenerator;
    private readonly OsduClientGenerator _osduClientGenerator;

    public CodeGenerator(ILogger<CodeGenerator> logger, AppConfiguration configuration, ApiGenerator apiGenerator,
        SchemaGenerator schemaGenerator, ServiceCollectionExtensionsGenerator servicesExtensionGenerator, OsduClientGenerator osduClientGenerator)
    {
        _logger = logger;
        _configuration = configuration;
        _apiGenerator = apiGenerator;
        _schemaGenerator = schemaGenerator;
        _servicesExtensionGenerator = servicesExtensionGenerator;
        _osduClientGenerator = osduClientGenerator;
    }

    public static void BuildAutogenComment(StringBuilder sb)
    {
        sb.AppendLine($$"""
                        // ==================================================================================================
                        // <auto-generated/>
                        // This code was generated by OSDU Client generator tool. 
                        // Do not modify it manually as the changes will be overwritten when the code is regenerated.
                        // ==================================================================================================

                        #nullable enable

                        """);
    }

    public void Generate()
    {
        GenerateApiClientsAndSchemas();
        GenerateDataSchemas();
    }

    private void GenerateApiClientsAndSchemas()
    {
        _logger.LogInformation("Generating API clients and schemas...");

        if (!Directory.Exists(_configuration.Api.DefinitionsDir))
        {
            _logger.LogError($"No API clients/schemas generated because API definitions directory not found: {_configuration.Api.DefinitionsDir}");
            return;
        }

        Directory.CreateDirectory(_configuration.Api.OutputDir);

        _logger.LogInformation($"  Reading API definitions from directory: {_configuration.Api.DefinitionsDir}");
        string[] jsonFiles = Directory.GetFiles(_configuration.Api.DefinitionsDir, "*.json", SearchOption.AllDirectories);

        _logger.LogInformation($"  Found {jsonFiles.Length} API definitions");

        var apiClientNames = new List<string>();

        foreach (string jsonFile in jsonFiles)
        {
            _logger.LogInformation($"  Building API client/schema from definition file: {jsonFile}");

            string apiClientName = Path.GetFileNameWithoutExtension(jsonFile).ToPascalCase();
            apiClientNames.Add(apiClientName);

            // Generate API client
            _apiGenerator.Generate(jsonFile, _configuration.Api.OutputDir, _configuration.Api.Namespace);

            // Generate API schema
            string outputDir = Path.Combine(_configuration.Api.OutputDir, apiClientName);
            string apiNamespace = $"{_configuration.Api.Namespace}.{apiClientName}";

            _schemaGenerator.GenerateNew(jsonFile, outputDir, apiNamespace);
        }

        // Generate the ServicesExtension class and IOsduClient/OsduClient
        if (apiClientNames.Count > 0)
        {
            _servicesExtensionGenerator.Generate(apiClientNames);
            _osduClientGenerator.Generate(apiClientNames);
        }
    }

    private void GenerateDataSchemas()
    {
        _logger.LogInformation("Generating data schemas...");

        if (!Directory.Exists(_configuration.Data.DefinitionsDir))
        {
            _logger.LogError($"No data schemas generated because data schema definitions directory not found: {_configuration.Data.DefinitionsDir}");
            return;
        }

        _logger.LogInformation($"  Reading data schema definitions from directory: {_configuration.Data.DefinitionsDir}");
        string[] jsonFiles = Directory.GetFiles(_configuration.Data.DefinitionsDir, "*.json", SearchOption.AllDirectories);

        _logger.LogInformation($"  Found {jsonFiles.Length} data schema definitions");

        int counter = 1;
        foreach (string jsonFile in jsonFiles)
        {
            _logger.LogInformation($"  Building data schema from definition file: {jsonFile}");

            string relativePath = Path.GetRelativePath(_configuration.Data.DefinitionsDir, jsonFile);
            string relativeDir = Path.GetDirectoryName(relativePath).ToPascalCase() ?? string.Empty;
            string outputDir = Path.Combine(_configuration.Data.OutputDir, relativeDir);
            string schemaNamespace = $"{_configuration.Data.Namespace}" + (relativeDir == "" ? "" : $".{relativeDir}");

            // Generate data schema
            _schemaGenerator.GenerateNew(jsonFile, outputDir, schemaNamespace, false);
        }

        // Apply cross-file inheritance patches after all data schemas are generated
        _schemaGenerator.ApplyCrossFilePatches(_configuration.Data.OutputDir);
    }
}
