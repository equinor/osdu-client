using System.Text;
using Microsoft.OpenApi;

namespace Osdu.Client.Generator.ConsoleApp.Generators.Api;

/// <summary>
/// Builds the top-level class structure (auto-gen comment, usings, interface, implementation wrapper).
/// </summary>
public class ApiClassBuilder
{
    private readonly ApiMethodGenerator _methodGenerator;

    public ApiClassBuilder(ApiMethodGenerator methodGenerator)
    {
        _methodGenerator = methodGenerator;
    }

    public void BuildAutogenComment(StringBuilder sb)
    {
        sb.AppendLine($$"""
                        // ==================================================================================================
                        // <auto-generated/>
                        // This code was generated by OSDU Client generator tool. 
                        // Do not modify it manually as the changes will be overwritten when the code is regenerated.
                        // ==================================================================================================
                        
                        #nullable enable
                        
                        """);
    }

    public void BuildUsingsAndNamespace(StringBuilder sb, string apiNamespace)
    {
        sb.AppendLine($$"""
                        using System;
                        using System.Collections.Generic;
                        using System.Net.Http;
                        using System.Net.Http.Json;
                        using System.Text;
                        using System.Text.Json;
                        using System.Text.Json.Serialization;
                        using System.Threading;
                        using System.Threading.Tasks;
                        using Osdu.Client.Validation;

                        namespace {{apiNamespace}};

                        """);
    }

    public void BuildInterface(StringBuilder sb, OpenApiDocument openApiDocument, string apiClientName)
    {
        sb.AppendLine($"public interface I{apiClientName}ApiClient");
        sb.AppendLine("{");

        foreach (var (path, pathItem) in openApiDocument.Paths)
        {
            foreach (var (method, operation) in pathItem.Operations!)
            {
                _methodGenerator.BuildMethodSignature(sb, path, method, operation, isInterface: true, pathItem);
            }
        }

        sb.AppendLine("}\n");
    }

    public void BuildImplementation(StringBuilder sb, OpenApiDocument openApiDocument, string apiClientName)
    {
        string defaultBaseUrl = openApiDocument.Servers?.FirstOrDefault()?.Url?.TrimEnd('/') ?? "";

        sb.AppendLine($$"""
                        public partial class {{apiClientName}}ApiClient : I{{apiClientName}}ApiClient
                        {
                            private readonly HttpClient _httpClient;
                            private readonly JsonSerializerOptions _jsonOptions;
                            private readonly string _baseUrl;

                            public {{apiClientName}}ApiClient(HttpClient httpClient)
                            {
                                _httpClient = httpClient ?? throw new ArgumentNullException(nameof(httpClient));
                                _baseUrl = "{{defaultBaseUrl}}";
                                _jsonOptions = new JsonSerializerOptions
                                {
                                    PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
                                    DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull
                                };
                            }

                        """);

        foreach (var (path, pathItem) in openApiDocument.Paths)
        {
            foreach (var (method, operation) in pathItem.Operations)
            {
                _methodGenerator.BuildMethod(sb, path, method, operation, pathItem);
            }
        }

        sb.AppendLine("}");
    }
}
